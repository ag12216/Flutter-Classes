class Validators {
  static String? validateEmail(String? email){
    
    var emailRegex = RegExp(r"^[a-zA-Z0-9.a-zA-Z0-9.!#$%&'*+-/=?^_`{|}~]+@[a-zA-Z0-9]+\.[a-zA-Z]+");
    
    if(emailRegex.hasMatch(email ?? '')){
      return null;
    }
    return "E-mail address is not valid";
  }
}